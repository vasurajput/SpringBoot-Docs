-- ----------------------------------------------------------------------------
-- 0. The building blocks, explained once before you see them in context
-- ----------------------------------------------------------------------------
--
-- A) ROW VARIABLES ("v_client public.t_geo_client;")
--    Declaring a variable with a table's name as its type gives you a variable
--    shaped exactly like one row of that table - one field per column, same
--    names, same types. Think of it like a Java object whose fields were
--    auto-generated from the table schema. You can read/write individual
--    fields (v_client.id, v_client.name) or refer to the whole row at once
--    (v_client.*) when you need every column.
--
-- B) SELECT ... INTO STRICT
--    Normally "SELECT ... INTO some_var" just runs a query and dumps the
--    result into a variable. STRICT adds a safety rule: the query MUST return
--    exactly one row, or Postgres raises an error for you automatically.
--      - 0 rows  -> error "no_data_found"   (without STRICT: silently leaves
--                                             the variable all-NULL - a bug
--                                             you'd never notice until later)
--      - 2+ rows -> error "too_many_rows"   (without STRICT: silently keeps
--                                             just the first row - also a bug)
--    This is why "template client must exist" needs zero extra IF-checks -
--    STRICT does that validation as a side effect of just fetching the row.
--
-- C) jsonb_populate_record(existing_row, json_object)
--    Takes a row variable and a JSON object, and returns a NEW row where:
--      - any column whose name matches a key in the JSON gets that JSON
--        value (cast into the column's real SQL type)
--      - any column NOT mentioned in the JSON keeps whatever value it
--        already had in existing_row
--    This is the entire "template + Excel overrides" mechanic in one line.
--    Two important gotchas:
--      1. If you pass NULL as existing_row, every unmentioned column just
--         stays NULL - that's how beneficiaries work (no template).
--      2. If the JSON has a key that ISN'T a real column name, it is
--         SILENTLY IGNORED by this function - no error. That's exactly why
--         the real function checks every JSON key against an allow-list by
--         hand BEFORE calling jsonb_populate_record (see step 2 below).
--
-- D) nextval('some_sequence')
--    A sequence is basically a shared, concurrency-safe counter living in
--    the database. Calling nextval() atomically bumps it and gives you the
--    new number - guaranteed unique even if two sessions call it at the same
--    instant. This is how a fresh primary key gets generated by hand instead
--    of relying on a column DEFAULT (which VALUES(v_client.*) bypasses).
--
-- E) INSERT ... RETURNING col INTO var
--    A normal INSERT doesn't tell you anything back. Adding "RETURNING id"
--    makes Postgres hand back the value that ended up in the id column of
--    the row it just inserted, and "INTO v_client_id" stores that value into
--    a variable so the rest of the function can use it. In our case we
--    already know the id (we set it ourselves with nextval in step D), but
--    RETURNING is the standard pattern - if id were auto-generated instead,
--    RETURNING would be the ONLY way to find out what it became.


