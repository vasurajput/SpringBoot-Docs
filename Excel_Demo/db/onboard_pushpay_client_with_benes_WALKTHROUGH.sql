--
--   SELECT * INTO STRICT v_client FROM public.t_geo_client
--   WHERE id = p_template_client_id;
--
--   -- v_client now holds a FULL COPY of every column from the template
--   -- client's row - name, address, all ~200 columns, everything.
--
--   v_client := jsonb_populate_record(v_client, p_client);
--
--   -- v_client is now: template's values, EXCEPT any field that p_client
--   -- (the JSON built from that Excel row) mentioned - those got overwritten.
--   -- This is "fields present in Excel override; everything else copied from
--   -- template" from design.md, done in a single function call.
--
--   v_client.id := nextval('cma_seq');   -- give it a brand-new id...
--   v_client.created_at := now();        -- ...and fresh system columns
--   -- (you'll add more resets here for whichever columns must NOT be carried
--   -- over verbatim from the template - see the real file's TODO)
--
--   INSERT INTO public.t_geo_client VALUES (v_client.*)
--   RETURNING id INTO v_client_id;
--
--   -- v_client_id is now the new client's real database id. This variable
--   -- stays alive for the rest of the function call - that's how step 3
--   -- below is able to just reuse it directly, no re-querying needed.


-- ----------------------------------------------------------------------------
-- 2. Validating the JSON BEFORE you trust it (why the allow-list loop exists)
-- ----------------------------------------------------------------------------
--
-- jsonb_populate_record (step 1C above) will happily ignore a JSON key that
-- doesn't match a real column - which means a typo'd or renamed Excel column
-- would silently vanish instead of erroring. To turn that into a loud
-- failure instead, the real function checks every key by hand FIRST:
--
--   FOR v_key IN SELECT jsonb_object_keys(p_client) LOOP
--       IF NOT (v_key = ANY (v_client_allowed_keys)) THEN
--           RAISE EXCEPTION 'Unknown client field "%"', v_key;
--       END IF;
--   END LOOP;
--
--   -- jsonb_object_keys(p_client) = "give me every key name in this JSON
--   -- object, one per row" - so this loop runs once per field Excel sent.
--   -- v_client_allowed_keys is just a plain text array declared up top
--   -- (ARRAY['name', 'client_address', ...]) - keep it in sync with
--   -- pushpay.client.columns in application.yml by hand (see design.md §8).
--
-- Two more validation layers happen "for free", without any extra code:
--   - RAISE EXCEPTION anywhere inside this function call aborts and rolls
--     back EVERYTHING that function call has done so far (the new client
--     row, any benes already inserted) - because it's all one transaction.
--     Other clients' SELECT statements elsewhere in the same batch.sql file
--     are untouched (each one is its own separate statement/transaction).
--   - If jsonb_populate_record tries to shove a JSON value into a column
--     whose real type can't hold it (e.g. text into a numeric column that
--     can't parse it), Postgres itself raises a cast error right there -
--     no code needed for that, it's automatic.
--   - If a NOT NULL column never gets a value (Excel left it blank and
--     there's no template to fall back on - i.e. beneficiaries), the plain
--     INSERT statement itself fails with a constraint violation. This is
--     why beneficiaries don't need their own allow-list-style NULL checking
--     in the function - the table schema enforces it as the last line of
--     defense, on top of the Java-side mandatory-field checks that should
--     normally catch it earlier.


